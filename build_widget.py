#!/usr/bin/env python3
"""Build widget.js (Scriptable) from logic.js + widget_main.js, and refresh the
copy box in widget.html. Run after editing logic.js or widget_main.js."""
import html, pathlib, re
root = pathlib.Path(__file__).resolve().parent
logic = (root / "logic.js").read_text()
main = (root / "widget_main.js").read_text()
header = """// Ticket Tracker widget for Scriptable (scriptable.app)
// Paste into a new Scriptable script, then add a Scriptable widget to your
// home screen and pick this script. Tap the widget to open the full tracker.
// Bets load live from tickets.json on every refresh: no need to re-paste for new bets.
// Stats: ESPN public game summaries. iOS decides real refresh timing.
// GENERATED by build_widget.py from logic.js + widget_main.js. Do not edit by hand.

"""
wrapped = "const TT = (function () {\n  const module = { exports: {} };\n" + logic + "\n  return module.exports;\n})();\n\n"
out = header + wrapped + main
(root / "widget.js").write_text(out)
page = (root / "widget.html").read_text()
new = re.sub(r'(<textarea id="code" readonly>)(.*?)(</textarea>)',
             lambda m: m.group(1) + html.escape(out, quote=True) + m.group(3), page, count=1, flags=re.S)
assert new != page or html.escape(out, quote=True) in page, "textarea not found"
(root / "widget.html").write_text(new)
print("widget.js", len(out), "bytes; widget.html updated")
